        private static GcnInstruction?[] IndexByOp(GcnInstruction[] instructions)
        {
            var byOp = new GcnInstruction?[Enum.GetValues<GcnOp>().Length];
            foreach (var instruction in instructions)
            {
                byOp[(int)instruction.Op] = byOp[(int)instruction.Op] is null
                    ? instruction
                    : throw new InvalidOperationException($"{instruction.Op} is in gfx9's table twice.");
            }

            return byOp;
        }
