"""Writes src/Idrak/Models/Tokenizers/UnicodeScripts.cs: the Unicode script of every code point, as sentencepiece 0.2.2's
trainer sees it (its unicode_script_map.h), so the unigram trainer refuses a piece that mixes scripts where SentencePiece
does (plan 24, T4).

    pip download sentencepiece==0.2.2 --no-binary :all: --no-deps -d sp && tar xzf sp/sentencepiece-0.2.2.tar.gz -C sp
    python -I tools/tokenizers/make_scripts.py sp/sentencepiece-0.2.2/sentencepiece/src/unicode_script_map.h

The table is written as ranges (each range's first code point and its script), Common where the map names none, as
sentencepiece's GetScript answers U_Common for a code point it does not list. Reruns write the same bytes.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "src", "Idrak", "Models", "Tokenizers", "UnicodeScripts.cs")
RANGE = re.compile(r"for \(char32_t c = 0x([0-9A-F]+); c <= 0x([0-9A-F]+); \+\+c\) \(\*smap\)\[c\] = U_(\w+);")
SINGLE = re.compile(r"\(\*smap\)\[0x([0-9A-F]+)\] = U_(\w+);")
# The scripts the trainer treats specially get fixed ids; the rest follow in name order.
FIXED = ["Common", "Inherited", "Han", "Hiragana", "Katakana"]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    scripts = {}
    with open(sys.argv[1], encoding="utf-8") as f:
        for line in f:
            if m := RANGE.search(line):
                for c in range(int(m[1], 16), int(m[2], 16) + 1):
                    scripts[c] = m[3]
            elif m := SINGLE.search(line):
                scripts[int(m[1], 16)] = m[2]
    names = FIXED + sorted(set(scripts.values()) - set(FIXED))
    ids = {name: i for i, name in enumerate(names)}
    assert len(names) < 256
    starts, values, previous = [], [], None
    for c in range(0x110000):
        s = scripts.get(c, "Common")
        if s != previous:
            starts.append(c)
            values.append(ids[s])
            previous = s

    def rows(items, width, per_line):
        lines = []
        for i in range(0, len(items), per_line):
            lines.append("        " + ", ".join(f"{x:#0{width}x}" if width else str(x) for x in items[i:i + per_line]) + ",")
        return "\n".join(lines)

    text = f"""// Copyright (c) 2026 Ahmed Seada
// Licensed under the Apache License, Version 2.0. See LICENSE in the repository root.

// Generated by tools/tokenizers/make_scripts.py from sentencepiece 0.2.2's unicode_script_map.h; do not edit.

namespace Idrak.Models;

/// <summary>
/// The Unicode script of a code point as sentencepiece 0.2.2's trainer sees it (<c>unicode_script::GetScript</c>): {len(starts):,}
/// ranges over {len(names)} scripts, Common where its map names none. The unigram trainer uses it to refuse a piece that mixes
/// scripts, as SentencePiece's <c>split_by_unicode_script</c> does.
/// </summary>
internal static class UnicodeScripts
{{
    /// <summary>The script sentencepiece answers for a code point it does not list.</summary>
    public const byte Common = 0;

    /// <summary>A combining mark that takes the script of the character before it.</summary>
    public const byte Inherited = 1;

    /// <summary>Han; the trainer counts Hiragana and Katakana (and U+30FC) as Han.</summary>
    public const byte Han = 2;

    /// <summary>Hiragana.</summary>
    public const byte Hiragana = 3;

    /// <summary>Katakana.</summary>
    public const byte Katakana = 4;

    // Each range's first code point, ascending; the range runs to the next one's.
    private static readonly int[] Starts =
    [
{rows(starts, 8, 10)}
    ];

    // Each range's script (an index into the names: {", ".join(names[:8])}, ...).
    private static readonly byte[] Scripts =
    [
{rows(values, 0, 24)}
    ];

    /// <summary>The script of <paramref name="codePoint"/>.</summary>
    public static byte Of(int codePoint)
    {{
        int at = Array.BinarySearch(Starts, codePoint);
        return Scripts[at >= 0 ? at : ~at - 1];
    }}
}}
"""
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"{OUT}: {len(starts)} ranges, {len(names)} scripts", file=sys.stderr)


if __name__ == "__main__":
    main()
