"""Plan 28's PDF samples and their expected results (phase D5): every sample is written here, byte for byte the same
from the seed and the pinned versions (tools/documents/requirements.txt), into an ignored folder; nothing generated is
committed.

    python -m pip install -r tools/documents/requirements.txt
    python -I tools/documents/make_fixtures.py -o test-output/documents/samples
    python -I tools/documents/make_fixtures.py --compare test-output/documents/run1 test-output/documents/run2

Writes, under the output folder (emptied first; a non-empty folder without a manifest.json is refused):
  d1/, d2/, d3/, d4/   each sample NAME.pdf with NAME.json (what it holds and what a reader must get), the reference
                       reader's and renderer's text (NAME.text.json), the reference renderer's pages (NAME.pN.png) and
                       the expected pixels of its images and the bytes of its attachments (NAME.*.png, NAME.<file>)
  manifest.json        every sample (kind, phases, files) and every file's size and SHA-256, and the versions that ran
See tools/documents/README.md for the JSON format.
"""
import argparse
import json
import os
import shutil
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True  # no __pycache__ left in the repository's tools folder
sys.path.insert(0, HERE)  # the docfixtures package beside this script (-I leaves the script's folder off the path)

ROOT = os.path.dirname(os.path.dirname(HERE))
DEFAULT_OUT = os.path.join(ROOT, "test-output", "documents", "samples")
SEED = "2026"
PHASES = ("d1", "d2", "d3", "d4")


def parse_args():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("-o", "--out", default=DEFAULT_OUT, help="the output folder (default: test-output/documents/samples)")
    ap.add_argument("--seed", default=SEED, help="the seed every generated byte comes from (default 2026)")
    ap.add_argument("--only", default=",".join(PHASES), help="phases to write, comma separated (default: d1,d2,d3,d4)")
    ap.add_argument("--no-reference", action="store_true", help="skip the reference tools (samples and JSON only)")
    ap.add_argument("--compare", nargs=2, metavar=("A", "B"), help="compare two output folders' manifests and files")
    ap.add_argument("--probe", nargs=2, metavar=("TOOL", "PDF"), help=argparse.SUPPRESS)
    ap.add_argument("--password", default=None, help=argparse.SUPPRESS)
    return ap.parse_args()


def versions():
    import zlib

    import cryptography
    import fontTools
    import PIL
    import pdfminer
    import pikepdf
    import pypdfium2
    import uharfbuzz
    from importlib.metadata import version

    return {
        "python": sys.version.split()[0], "zlib": zlib.ZLIB_RUNTIME_VERSION,
        "pikepdf": pikepdf.__version__, "qpdf": pikepdf.__libqpdf_version__, "pdfminer.six": pdfminer.__version__,
        "pypdfium2": version("pypdfium2"), "pdfium": str(pypdfium2.version.PDFIUM_INFO),
        "fonttools": fontTools.version, "pillow": PIL.__version__, "cryptography": cryptography.__version__,
        "uharfbuzz": uharfbuzz.__version__, "harfbuzz": uharfbuzz.version_string(), "python-bidi": version("python-bidi"),
    }


def dump(obj):
    return (json.dumps(obj, ensure_ascii=False, indent=1) + "\n").encode("utf-8")


def prepare(out):
    if os.path.isdir(out) and os.listdir(out):
        if not os.path.isfile(os.path.join(out, "manifest.json")):
            sys.exit(f"{out} is not empty and holds no manifest.json: not a samples folder, left alone")
        print(f"emptying {out} (a previous run)", flush=True)
        shutil.rmtree(out)
    os.makedirs(out, exist_ok=True)


def progress(i, n, start, what):
    done = i + 1
    elapsed = time.monotonic() - start
    rate = done / elapsed if elapsed > 0 else 0.0
    left = (n - done) / rate if rate > 0 else 0.0
    print(f"[{done:3d}/{n}] {what:<58} {elapsed:6.1f}s elapsed, {rate:5.2f}/s, ~{left:5.1f}s left", flush=True)


def reference(sample, folder, script, notes):
    """Runs the reference tools on one written sample and adds their results to its JSON (and files beside it)."""
    from docfixtures import reference as ref
    from docfixtures.png import png_bytes

    path = os.path.join(folder, sample.file)
    exp = sample.expected
    if sample.hostile is not None or exp.get("openError"):
        password = exp.get("open", {}).get("password") if exp.get("open") else None
        exp["reference"] = {"outcomes": ref.probe(script, path, password)}
        return {}
    password = exp["open"]["password"]
    files = {}
    pike = ref.pikepdf_check(path, password, exp["streams"])
    if pike.get("streamMismatches"):
        notes.append(f"{sample.folder}/{sample.name}: qpdf decodes {len(pike['streamMismatches'])} stream(s) differently")
    if not pike.get("opened"):
        notes.append(f"{sample.folder}/{sample.name}: qpdf could not open it: {pike.get('error')}")
    miner, miner_error = None, None
    try:
        miner = ref.pdfminer_text(path, password)
    except Exception as e:  # noqa: BLE001 - recorded
        miner_error = ref._msg(e, path)
        notes.append(f"{sample.folder}/{sample.name}: pdfminer.six failed: {miner_error}")
    pdfium, pdfium_error = None, None
    try:
        pdfium = ref.pdfium_run(path, password)
    except Exception as e:  # noqa: BLE001 - recorded
        pdfium_error = ref._msg(e, path)
        notes.append(f"{sample.folder}/{sample.name}: pdfium failed: {pdfium_error}")
    pngs = []
    box_check = []
    if pdfium:
        for e in pdfium["errors"]:
            notes.append(f"{sample.folder}/{sample.name}: pdfium could not load page {e['page'] + 1}: {e['error']}")
        for pg in pdfium["pages"]:
            k = pg["index"]
            name = f"{sample.name}.p{k + 1}.png"
            img = pg["image"]
            files[name] = png_bytes(img.width, img.height, 3, 8, img.tobytes())
            pngs.append(name)
            if k < len(exp["pages"]):
                dx, dy, matched = ref.check_boxes(exp["pages"][k], pg["chars"], ref.geometry(exp["pages"][k]))
                box_check.append({"page": k, "runsMatched": matched, "runs": len(exp["pages"][k]["runs"]),
                                  "largestDifferenceX": dx, "largestDifferenceY": dy})
    text = {"pdfminer": miner, "pdfium": [pg["text"] for pg in pdfium["pages"]] if pdfium else None}
    files[f"{sample.name}.text.json"] = dump(text)
    exp["reference"] = {
        "dpi": ref.DPI, "text": f"{sample.name}.text.json", "pages": pngs,
        "qpdf": pike, "pdfminer": {"opened": miner is not None, "error": miner_error,
                                   "pages": len(miner) if miner else None},
        "pdfium": {"opened": pdfium is not None, "error": pdfium_error,
                   "pageCount": pdfium["pageCount"] if pdfium else None,
                   "rendered": len(pdfium["pages"]) if pdfium else 0,
                   "pageErrors": pdfium["errors"] if pdfium else [], "boxes": box_check},
    }
    return files


def compare(a, b):
    ma = json.load(open(os.path.join(a, "manifest.json"), encoding="utf-8"))
    mb = json.load(open(os.path.join(b, "manifest.json"), encoding="utf-8"))
    fa = {f["path"]: f["sha256"] for f in ma["files"]}
    fb = {f["path"]: f["sha256"] for f in mb["files"]}
    diffs = [p for p in sorted(set(fa) | set(fb)) if fa.get(p) != fb.get(p)]
    same_manifest = open(os.path.join(a, "manifest.json"), "rb").read() == open(os.path.join(b, "manifest.json"), "rb").read()
    print(f"{len(fa)} files in {a}, {len(fb)} in {b}; manifests identical: {same_manifest}; differing files: {len(diffs)}")
    for p in diffs[:50]:
        print(f"  differs: {p}")
    return 0 if not diffs and same_manifest else 1


def main():
    args = parse_args()
    if args.probe:
        from docfixtures.reference import probe_child

        probe_child(args.probe[0], args.probe[1], args.password)
        return 0
    if args.compare:
        return compare(*args.compare)
    from docfixtures import samples_d1, samples_d2, samples_d3, samples_d4

    out = os.path.abspath(args.out)
    prepare(out)
    builders = {"d1": samples_d1.build, "d2": samples_d2.build, "d3": samples_d3.build, "d4": samples_d4.build}
    wanted = [p.strip() for p in args.only.split(",") if p.strip()]
    start = time.monotonic()
    samples = []
    for phase in wanted:
        print(f"making the {phase.upper()} samples", flush=True)
        samples += builders[phase](args.seed)
    print(f"{len(samples)} samples made in {time.monotonic() - start:.1f}s; writing them and running the reference "
          "tools", flush=True)
    script = os.path.abspath(__file__)
    notes = []
    entries = []
    ref_start = time.monotonic()
    for i, s in enumerate(samples):
        folder = os.path.join(out, s.folder)
        os.makedirs(folder, exist_ok=True)
        with open(os.path.join(folder, s.file), "wb") as f:
            f.write(s.data)
        files = dict(s.files)
        if not args.no_reference:
            files.update(reference(s, folder, script, notes))
        for name, data in sorted(files.items()):
            with open(os.path.join(folder, name), "wb") as f:
                f.write(data)
        s.expected["files"] = sorted(files)
        with open(os.path.join(folder, f"{s.name}.json"), "wb") as f:
            f.write(dump(s.expected))
        entries.append({"name": s.name, "folder": s.folder, "file": f"{s.folder}/{s.file}", "kind": s.kind,
                        "phases": s.phases, "hostile": s.hostile is not None,
                        "expected": f"{s.folder}/{s.name}.json",
                        "files": [f"{s.folder}/{n}" for n in sorted(files)], "size": len(s.data),
                        "sha256": s.expected["sha256"]})
        progress(i, len(samples), ref_start, f"{s.folder}/{s.file}")
    from docfixtures.pdf import sha256

    listing = []
    for dirpath, _, names in os.walk(out):
        for n in names:
            full = os.path.join(dirpath, n)
            rel = os.path.relpath(full, out).replace(os.sep, "/")
            if rel == "manifest.json":
                continue
            data = open(full, "rb").read()
            listing.append({"path": rel, "size": len(data), "sha256": sha256(data)})
    listing.sort(key=lambda e: e["path"])
    manifest = {"schema": 1, "generator": "tools/documents/make_fixtures.py", "seed": args.seed,
                "renderDpi": 100, "reference": not args.no_reference, "versions": versions(), "samples": entries,
                "files": listing}
    with open(os.path.join(out, "manifest.json"), "wb") as f:
        f.write(dump(manifest))
    by_phase = {}
    for e in entries:
        for p in e["phases"]:
            by_phase[p] = by_phase.get(p, 0) + 1
    hostile = sum(1 for e in entries if e["hostile"])
    print(f"done: {len(entries)} samples ({hostile} hostile), {len(listing) + 1} files, by phase "
          + ", ".join(f"{k} {v}" for k, v in sorted(by_phase.items()))
          + f", in {time.monotonic() - start:.1f}s; written to {out}", flush=True)
    for n in notes:
        print(f"note: {n}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
