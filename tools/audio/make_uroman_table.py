"""uroman's romanisation of Arabic script, for the VITS plug-in (plan 21, decision 3): MMS-TTS checkpoints whose
tokenizer_config.json sets is_uroman (facebook/mms-tts-ara among them) were trained on text romanised by uroman, so
the plug-in romanises Arabic the same way before tokenizing.

    python -m venv uroman && uroman/bin/pip install uroman
    uroman/bin/python tools/audio/make_uroman_table.py

Writes samples/VitsSpeech/Idrak.VitsSpeech/UromanArabicTable.cs (the romanisation of every code point of the Arabic
blocks that uroman changes) and tests/Idrak.Tests/data/audio/uroman/arabic.json (sentences, diacritised words,
digits, presentation forms, decomposed sequences and seeded random strings with uroman's output for each: the
plug-in must give the same). uroman romanises Arabic character by character, but for a few sequences its
romanization-table.txt names without a language code (MMS-TTS calls uroman without one): alef + fathatan "an",
maddah + alef, a word-initial alef + Persian yeh. The tool copies those rules, with their word-start and word-end
conditions, into the table's Rules; the cases check every one.
"""
import re
import json
import os
import random
import sys
import unicodedata

import uroman as ur

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RANGES = [(0x0600, 0x06FF), (0x0750, 0x077F), (0x0870, 0x089F), (0x08A0, 0x08FF), (0xFB50, 0xFDFF), (0xFE70, 0xFEFF)]

SENTENCES = [
    "حسب الذمة جدة. الإقامة عبر 1407 هـ. سعود بن خديجة",
    "كذلك قدمت النقض مع صاحب عنيزة إدارة العامة قبل الديوان اللازمة",
    "وفق ينبع قبل الرهن. كانت تكون القرار",
    "لم حضر قرار عليه الموظف أرفق الشهادة الرسمية",
    "مرحبا بكم في إدراك، كيف حالكم اليوم؟",
    "السَّلامُ عَلَيْكُمْ وَرَحْمَةُ اللَّهِ وَبَرَكَاتُهُ",
    "العربيةُ لغةٌ جميلةٌ: ١٢٣٤٥٦٧٨٩٠ و۱۲۳",
    "مسؤولٌ سائلٌ شيءٌ سماءً قرأ مستشفى",
    "ﻻ إله إلا ﷲ، ﷺ",
    "گچپژ ڤ ڭ",
    "Ab مرحبا cD 😀",
    "تـــطويل",
    "آ ؤ ئ إ",       # decomposed madda and hamzas (NFC would compose them)
    "آ ؤ ئ إ",
    "كتاباً جميلاً اً باً بًا",              # alef + fathatan, and fathatan before alef
    "\u0653\u0627 ب\u0653\u0627",          # maddah + alef
    "ایران بای ای",                          # alef + Persian yeh at the start of a word and inside one
    "خانهٔ هٔ",
]


def multi_rules():
    """romanization-table.txt's rules for two or more Arabic-script characters with no ::lcode: (source, target, condition)."""
    arabic = re.compile(r"[\u0600-\u06FF\u0750-\u077F\u0870-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]")
    path = os.path.join(os.path.dirname(ur.__file__), "data", "romanization-table.txt")
    rules = []
    for line in open(path, encoding="utf-8"):
        m = re.search(r"::s\s+(\S+)\s+::t\s+(\S*)", line)
        if not m or "::lcode" in line or len(arabic.findall(m.group(1))) < 2:
            continue
        condition = "start" if "::use-only-at-start-of-word" in line else "end" if "::use-only-at-end-of-word" in line else "any"
        rules.append((m.group(1), m.group(2), condition))
    return rules


def main():
    u = ur.Uroman()
    table = {}
    for a, b in RANGES:
        for cp in range(a, b + 1):
            c = chr(cp)
            try:
                unicodedata.name(c)
            except ValueError:
                continue
            out = u.romanize_string(c)
            if out != c:
                table[cp] = out
    version = getattr(ur, "__version__", None) or __import__("importlib.metadata").metadata.version("uroman")
    lines = "".join(f"{cp:04X}\t{out}\n" for cp, out in sorted(table.items()))
    rules = multi_rules()
    for source, target, condition in rules:
        if condition == "any":
            assert u.romanize_string(source) == target, (source, target, u.romanize_string(source))
    rule_lines = "".join(f"{' '.join(f'{ord(c):04X}' for c in source)}\t{target}\t{condition}\n" for source, target, condition in rules)
    cs = f'''// Copyright (c) 2026 Ahmed Seada
// Licensed under the Apache License, Version 2.0. See LICENSE in the repository root.

// Generated by tools/audio/make_uroman_table.py from uroman {version}: do not edit by hand.

namespace Idrak.VitsSpeech;

internal static class UromanArabicTable
{{
    /// <summary>The uroman version the table was made from.</summary>
    public const string Version = "{version}";

    /// <summary>One line per code point uroman changes: its hexadecimal value, a tab, its romanisation (empty: dropped).</summary>
    public const string Entries = """
{lines}""";

    /// <summary>
    /// uroman's rules for sequences (no language code): the code points in hexadecimal separated by spaces, a tab, the
    /// romanisation, a tab, where it applies (any, start or end of a word).
    /// </summary>
    public const string Rules = """
{rule_lines}""";
}}
'''
    with open(os.path.join(ROOT, "samples", "VitsSpeech", "Idrak.VitsSpeech", "UromanArabicTable.cs"), "w", encoding="utf-8", newline="\n") as f:
        f.write(cs)

    rng = random.Random(2029)
    letters = [chr(cp) for cp in range(0x0621, 0x064B)] + [chr(cp) for cp in range(0x064B, 0x0653)] + [" ", " ", "،", "؟", "0", "١"]
    cases = list(SENTENCES)
    for _ in range(200):
        cases.append("".join(rng.choice(letters) for _ in range(rng.randint(1, 24))))
    rows = [{"text": s, "uroman": u.romanize_string(s)} for s in cases]
    with open(os.path.join(ROOT, "tests", "Idrak.Tests", "data", "audio", "uroman", "arabic.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump({"uroman": version, "cases": rows}, f, ensure_ascii=False, indent=1, sort_keys=True)
        f.write("\n")
    print(f"{len(table)} code points, {len(rules)} sequence rules, {len(rows)} cases, uroman {version}")


if __name__ == "__main__":
    sys.exit(main())
