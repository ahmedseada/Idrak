"""The constant tables of the MP3 plug-in (samples/Mp3Audio), copied from minimp3 (https://github.com/lieff/minimp3,
CC0: public domain) so no value is typed by hand: the scale-factor band widths, the Huffman trees, the
dequantisation, stereo, alias, IMDCT and synthesis constants, and the Layer II allocation tables.

    python tools/audio/make_mp3_tables.py path/to/minimp3.h

minimp3.h comes with the minimp3-sys crate (crates.io) or the minimp3 repository. Writes
samples/Mp3Audio/Idrak.Mp3Audio/Mp3Tables.cs.
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

# minimp3 name -> (C# name, C# element type)
TABLES = {
    "halfrate": ("HalfRate", "byte"),
    "g_scf_long": ("ScfLong", "byte"),
    "g_scf_short": ("ScfShort", "byte"),
    "g_scf_mixed": ("ScfMixed", "byte"),
    "g_scf_partitions": ("ScfPartitions", "byte"),
    "g_scfc_decode": ("ScfcDecode", "byte"),
    "g_mod": ("Mod", "byte"),
    "g_preamp": ("Preamp", "byte"),
    "g_expfrac": ("ExpFrac", "float"),
    "g_pow43": ("Pow43", "float"),
    "tabs": ("Tabs", "short"),
    "tab32": ("Tab32", "byte"),
    "tab33": ("Tab33", "byte"),
    "tabindex": ("TabIndex", "short"),
    "g_linbits": ("Linbits", "byte"),
    "g_pan": ("Pan", "float"),
    "g_aa": ("Aa", "float"),
    "g_twid9": ("Twid9", "float"),
    "g_twid3": ("Twid3", "float"),
    "g_mdct_window": ("MdctWindow", "float"),
    "g_sec": ("Sec", "float"),
    "g_win": ("Win", "float"),
    "g_bitalloc_code_tab": ("BitallocCodeTab", "byte"),
}


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = open(sys.argv[1], encoding="utf-8").read()
    source = re.sub(r"/\*.*?\*/", "", source, flags=re.S)
    out = []
    for c_name, (cs_name, kind) in TABLES.items():
        m = re.search(r"static const \w+ " + re.escape(c_name) + r"\s*((?:\[[^\]]*\])+)\s*=\s*\{(.*?)\};", source, re.S)
        if not m:
            sys.exit(f"{c_name} not found in {sys.argv[1]}")
        number = r"-?\d+(?:\.\d+)?(?:e-?\d+)?f?"
        dims = re.findall(r"\[([^\]]*)\]", m.group(1))
        rows_in = re.findall(r"\{([^{}]*)\}", m.group(2))
        if len(dims) == 2 and rows_in:
            width = int(eval(dims[1]))                      # C zero-fills a row shorter than its declared width
            values = []
            for row in rows_in:
                found = re.findall(number, row)
                values += found + ["0"] * (width - len(found))
        else:
            values = re.findall(number, m.group(2).replace("{", " ").replace("}", " "))
        if kind == "float":
            values = [v if v.endswith("f") else v + "f" for v in values]
            values = [v if "." in v or "e" in v else v[:-1] + ".0f" for v in values]
        rows = [", ".join(values[i:i + 16]) for i in range(0, len(values), 16)]
        body = ",\n        ".join(rows)
        out.append(f"    /// <summary>minimp3's <c>{c_name}</c> ({len(values)} values).</summary>\n"
                   f"    internal static readonly {kind}[] {cs_name} =\n    [\n        {body},\n    ];\n")
    cs = ("// Copyright (c) 2026 Ahmed Seada\n"
          "// Licensed under the Apache License, Version 2.0. See LICENSE in the repository root.\n\n"
          "// Generated by tools/audio/make_mp3_tables.py from minimp3 (https://github.com/lieff/minimp3, CC0, public domain):\n"
          "// do not edit by hand.\n\n"
          "namespace Idrak.Mp3Audio;\n\n"
          "internal static class Mp3Tables\n{\n" + "\n".join(out) + "}\n")
    path = os.path.join(ROOT, "samples", "Mp3Audio", "Idrak.Mp3Audio", "Mp3Tables.cs")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(cs)
    print(f"wrote {path}: {len(TABLES)} tables")


if __name__ == "__main__":
    main()
